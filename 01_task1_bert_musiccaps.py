    predictions = (val_probs >= threshold).astype(int)

    micro = f1_score(
        val_labels,
        predictions,
        average="micro",
        zero_division=0
    )

    macro = f1_score(
        val_labels,
        predictions,
        average="macro",
        zero_division=0
    )

    threshold_results.append(
        (threshold, micro, macro)
    )

    print(
        f"Threshold={threshold:.2f} | "
        f"Micro-F1={micro:.4f} | "
        f"Macro-F1={macro:.4f}"
    )

