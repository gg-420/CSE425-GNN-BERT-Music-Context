import librosa
import numpy as np
import torch
import torch.nn.functional as F


MEL_SR = 22050
MEL_SECONDS = 30
N_MELS = 128


def create_logmel(audio_path):

    # Load audio
    audio, sr = librosa.load(
        audio_path,
        sr=MEL_SR,
        mono=True
    )

    # Make exactly 30 seconds
    target_length = (
        MEL_SR * MEL_SECONDS
    )

    if len(audio) < target_length:

        audio = np.pad(
            audio,
            (
                0,
                target_length - len(audio)
            )
        )

    else:

        audio = audio[:target_length]

    # Mel spectrogram
    mel = librosa.feature.melspectrogram(
        y=audio,
        sr=MEL_SR,
        n_fft=1024,
        hop_length=512,
        n_mels=N_MELS
    )

    # Convert power to logarithmic dB
    logmel = librosa.power_to_db(
        mel,
        ref=np.max
    )

    # Normalize per track
    logmel = (
        logmel - logmel.mean()
    ) / (
        logmel.std() + 1e-6
    )

    # Tensor:
    # [1, 128, time]
    tensor = torch.tensor(
        logmel,
        dtype=torch.float32
    ).unsqueeze(0)

    # Resize time dimension for
    # efficient CNN training
    tensor = tensor.unsqueeze(0)

    tensor = F.interpolate(
        tensor,
        size=(128, 256),
        mode="bilinear",
        align_corners=False
    )

    tensor = tensor.squeeze(0)

    return tensor

