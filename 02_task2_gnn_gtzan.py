SR = 22050
TARGET_SECONDS = 30
SEGMENT_SECONDS = 5
NUM_SEGMENTS = 6
SIMILARITY_THRESHOLD = 0.99


def build_music_graph(audio_path, genre_name):

    # -------------------------
    # 1. Load audio
    # -------------------------
    audio, sr = librosa.load(
        audio_path,
        sr=SR,
        mono=True
    )

    # -------------------------
    # 2. Make exactly 30 sec
    # -------------------------
    target_length = TARGET_SECONDS * SR

    if len(audio) < target_length:
        audio = np.pad(
            audio,
            (0, target_length - len(audio))
        )
    else:
        audio = audio[:target_length]

    # -------------------------
    # 3. Divide into 6 segments
    # -------------------------
    segment_length = SEGMENT_SECONDS * SR

    node_features = []

    for i in range(NUM_SEGMENTS):

        start = i * segment_length
        end = start + segment_length

        segment = audio[start:end]

        # -------------------------
        # 4. Chroma features
        # -------------------------
        chroma = librosa.feature.chroma_stft(
            y=segment,
            sr=SR,
            n_chroma=12
        )

        chroma_mean = np.mean(
            chroma,
            axis=1
        )

        node_features.append(chroma_mean)

    node_features = np.array(
        node_features,
        dtype=np.float32
    )

    # -------------------------
    # 5. Similarity matrix
    # -------------------------
    similarity_matrix = cosine_similarity(
        node_features
    )

    edge_set = set()

    # -------------------------
    # 6. Temporal edges
    # -------------------------
    for i in range(NUM_SEGMENTS - 1):

        edge_set.add((i, i + 1))
        edge_set.add((i + 1, i))

    # -------------------------
    # 7. Similarity edges
    # -------------------------
    for i in range(NUM_SEGMENTS):

        for j in range(i + 1, NUM_SEGMENTS):

            if j == i + 1:
                continue

            if (
                similarity_matrix[i, j]
                >= SIMILARITY_THRESHOLD
            ):

                edge_set.add((i, j))
                edge_set.add((j, i))

    edge_index = np.array(
        sorted(list(edge_set)),
        dtype=np.int64
    ).T

    # -------------------------
    # 8. PyTorch Geometric graph
    # -------------------------
    graph = Data(

        x=torch.tensor(
            node_features,
            dtype=torch.float
        ),

        edge_index=torch.tensor(
            edge_index,
            dtype=torch.long
        ),

        y=torch.tensor(
            [genre_to_id[genre_name]],
            dtype=torch.long
        )
    )

    return graph

