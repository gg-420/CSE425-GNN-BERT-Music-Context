import torch.nn as nn
import torch.nn.functional as F


class MelCNN(nn.Module):

    def __init__(
        self,
        num_classes=10
    ):

        super().__init__()

        self.conv1 = nn.Conv2d(
            1,
            16,
            kernel_size=3,
            padding=1
        )

        self.bn1 = nn.BatchNorm2d(16)

        self.conv2 = nn.Conv2d(
            16,
            32,
            kernel_size=3,
            padding=1
        )

        self.bn2 = nn.BatchNorm2d(32)

        self.conv3 = nn.Conv2d(
            32,
            64,
            kernel_size=3,
            padding=1
        )

        self.bn3 = nn.BatchNorm2d(64)

        self.pool = nn.MaxPool2d(2)

        self.adaptive_pool = (
            nn.AdaptiveAvgPool2d(
                (4, 4)
            )
        )

        self.fc1 = nn.Linear(
            64 * 4 * 4,
            128
        )

        self.dropout = nn.Dropout(0.3)

        self.fc2 = nn.Linear(
            128,
            num_classes
        )


    def forward(self, x):

        x = self.pool(
            F.relu(
                self.bn1(
                    self.conv1(x)
                )
            )
        )

        x = self.pool(
            F.relu(
                self.bn2(
                    self.conv2(x)
                )
            )
        )

        x = self.pool(
            F.relu(
                self.bn3(
                    self.conv3(x)
                )
            )
        )

        x = self.adaptive_pool(x)

        x = torch.flatten(
            x,
            start_dim=1
        )

        x = F.relu(
            self.fc1(x)
        )

        x = self.dropout(x)

        return self.fc2(x)

