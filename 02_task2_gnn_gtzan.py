def train_one_epoch():

    model.train()

    total_loss = 0

    for batch in train_loader:

        batch = batch.to(device)

        optimizer.zero_grad()

        output = model(
            batch.x,
            batch.edge_index,
            batch.batch
        )

        labels = batch.y.view(-1)

        loss = criterion(
            output,
            labels
        )

        loss.backward()

        optimizer.step()

        total_loss += (
            loss.item()
            * batch.num_graphs
        )

    return (
        total_loss
        / len(train_loader.dataset)
    )

from sklearn.metrics import (
    accuracy_score,
    f1_score
)


@torch.no_grad()
def evaluate(loader):

    model.eval()

    all_true = []
    all_pred = []

    total_loss = 0

    for batch in loader:

        batch = batch.to(device)

        output = model(
            batch.x,
            batch.edge_index,
            batch.batch
        )

        labels = batch.y.view(-1)

        loss = criterion(
            output,
            labels
        )

        total_loss += (
            loss.item()
            * batch.num_graphs
        )

        predictions = (
            output.argmax(dim=1)
        )

        all_true.extend(
            labels.cpu().numpy()
        )

        all_pred.extend(
            predictions.cpu().numpy()
        )

    average_loss = (
        total_loss
        / len(loader.dataset)
    )

    accuracy = accuracy_score(
        all_true,
        all_pred
    )

    macro_f1 = f1_score(
        all_true,
        all_pred,
        average="macro",
        zero_division=0
    )

    micro_f1 = f1_score(
        all_true,
        all_pred,
        average="micro",
        zero_division=0
    )

    return (
        average_loss,
        accuracy,
        macro_f1,
        micro_f1,
        all_true,
        all_pred
    )

