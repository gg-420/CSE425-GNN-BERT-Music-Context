def train_cnn_epoch():

    cnn_model.train()

    total_loss = 0

    for inputs, labels in (
        cnn_train_loader
    ):

        inputs = inputs.to(device)
        labels = labels.to(device)

        cnn_optimizer.zero_grad()

        outputs = cnn_model(
            inputs
        )

        loss = cnn_criterion(
            outputs,
            labels
        )

        loss.backward()

        cnn_optimizer.step()

        total_loss += (
            loss.item()
            * inputs.size(0)
        )

    return (
        total_loss
        / len(cnn_train_dataset)
    )

from sklearn.metrics import (
    accuracy_score,
    f1_score
)


@torch.no_grad()
def evaluate_cnn(loader):

    cnn_model.eval()

    all_true = []
    all_pred = []

    total_loss = 0

    for inputs, labels in loader:

        inputs = inputs.to(device)
        labels = labels.to(device)

        outputs = cnn_model(
            inputs
        )

        loss = cnn_criterion(
            outputs,
            labels
        )

        total_loss += (
            loss.item()
            * inputs.size(0)
        )

        predictions = (
            outputs.argmax(dim=1)
        )

        all_true.extend(
            labels.cpu().numpy()
        )

        all_pred.extend(
            predictions.cpu().numpy()
        )

    avg_loss = (
        total_loss
        / len(loader.dataset)
    )

    accuracy = accuracy_score(
        all_true,
        all_pred
    )

    macro_f1 = f1_score(
        all_true,
        all_pred,
        average="macro",
        zero_division=0
    )

    micro_f1 = f1_score(
        all_true,
        all_pred,
        average="micro",
        zero_division=0
    )

    return (
        avg_loss,
        accuracy,
        macro_f1,
        micro_f1,
        all_true,
        all_pred
    )

