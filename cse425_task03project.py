class Task3GraphSAGE(nn.Module):

    def __init__(
        self,
        input_dim=12,
        hidden_dim=128,
        num_labels=50,
        dropout=0.3
    ):

        super().__init__()

        self.conv1 = SAGEConv(
            input_dim,
            hidden_dim
        )

        self.conv2 = SAGEConv(
            hidden_dim,
            hidden_dim
        )

        self.dropout = nn.Dropout(
            dropout
        )

        self.classifier = nn.Linear(
            hidden_dim,
            num_labels
        )


    def encode(
        self,
        x,
        edge_index,
        batch
    ):

        x = self.conv1(
            x,
            edge_index
        )

        x = F.relu(x)

        x = self.dropout(x)

        x = self.conv2(
            x,
            edge_index
        )

        x = F.relu(x)

        return global_mean_pool(
            x,
            batch
        )


    def forward(
        self,
        x,
        edge_index,
        batch
    ):

        g = self.encode(
            x,
            edge_index,
            batch
        )

        return self.classifier(g)


