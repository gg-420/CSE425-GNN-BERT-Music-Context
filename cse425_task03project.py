# ------------------------------------------------------------
# CROSS ATTENTION MODEL
# ------------------------------------------------------------

class CrossAttentionFusion(nn.Module):

    def __init__(
        self,
        graph_dim=128,
        bert_dim=768,
        num_heads=8,
        hidden_dim=256,
        num_labels=50,
        dropout=0.3
    ):

        super().__init__()


        # Graph embedding becomes query
        self.graph_projection = nn.Linear(
            graph_dim,
            bert_dim
        )


        # Graph query attends over
        # BERT token embeddings
        self.cross_attention = (
            nn.MultiheadAttention(
                embed_dim=bert_dim,
                num_heads=num_heads,
                dropout=0.1,
                batch_first=True
            )
        )


        self.norm = nn.LayerNorm(
            bert_dim * 2
        )


        self.fc = nn.Linear(
            bert_dim * 2,
            hidden_dim
        )


        self.dropout = nn.Dropout(
            dropout
        )


        self.classifier = nn.Linear(
            hidden_dim,
            num_labels
        )


    def forward(
        self,
        graph_embedding,
        input_ids,
        attention_mask,
        return_attention=False
    ):

        # -----------------------------
        # Frozen BERT
        # -----------------------------

        with torch.no_grad():

            _, token_embeddings = (
                bert_model.encode(
                    input_ids,
                    attention_mask
                )
            )


        token_embeddings = (
            token_embeddings.detach()
        )


        # -----------------------------
        # Graph query
        # [B, 128] -> [B, 1, 768]
        # -----------------------------

        graph_query = (
            self.graph_projection(
                graph_embedding
            )
            .unsqueeze(1)
        )


        padding_mask = (
            attention_mask == 0
        )


        # -----------------------------
        # Cross Attention
        # -----------------------------

        if return_attention:

            attended, weights = (
                self.cross_attention(
                    query=graph_query,
                    key=token_embeddings,
                    value=token_embeddings,
                    key_padding_mask=
                        padding_mask,
                    need_weights=True,
                    average_attn_weights=False
                )
            )

        else:

            attended, _ = (
                self.cross_attention(
                    query=graph_query,
                    key=token_embeddings,
                    value=token_embeddings,
                    key_padding_mask=
                        padding_mask,
                    need_weights=False
                )
            )

            weights = None


        graph_vector = (
            graph_query.squeeze(1)
        )

        attended_vector = (
            attended.squeeze(1)
        )


        # -----------------------------
        # Fusion
        # -----------------------------

        fused = torch.cat(
            [
                graph_vector,
                attended_vector
            ],
            dim=1
        )


        fused = self.norm(
            fused
        )


        z = F.relu(
            self.fc(
                fused
            )
        )


        z = self.dropout(
            z
        )


        logits = self.classifier(
            z
        )


        if return_attention:

            return (
                logits,
                z,
                weights
            )


        return logits, z


