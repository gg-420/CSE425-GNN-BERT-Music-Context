class Task3BERTOnly(nn.Module):

    def __init__(
        self,
        config,
        num_labels=50,
        dropout=0.2
    ):

        super().__init__()

        self.bert = AutoModel.from_config(
            config
        )

        hidden_size = (
            config.hidden_size
        )

        self.dropout = nn.Dropout(
            dropout
        )

        self.classifier = nn.Linear(
            hidden_size,
            num_labels
        )


    def encode(
        self,
        input_ids,
        attention_mask
    ):

        output = self.bert(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        token_embeddings = (
            output.last_hidden_state
        )

        text_embedding = (
            token_embeddings[:, 0, :]
        )

        return (
            text_embedding,
            token_embeddings
        )


    def forward(
        self,
        input_ids,
        attention_mask
    ):

        text_embedding, _ = self.encode(
            input_ids,
            attention_mask
        )

        text_embedding = self.dropout(
            text_embedding
        )

        return self.classifier(
            text_embedding
        )


