# ------------------------------------------------------------
# End-to-end model
# ------------------------------------------------------------

class EndToEndCrossAttention(nn.Module):

    def __init__(
        self,
        gnn,
        bert_backbone,
        pretrained_fusion
    ):

        super().__init__()

        self.gnn = gnn

        self.bert = bert_backbone

        # Start from our already-trained
        # cross-attention fusion weights
        self.graph_projection = copy.deepcopy(
            pretrained_fusion.graph_projection
        )

        self.cross_attention = copy.deepcopy(
            pretrained_fusion.cross_attention
        )

        self.norm = copy.deepcopy(
            pretrained_fusion.norm
        )

        self.fc = copy.deepcopy(
            pretrained_fusion.fc
        )

        self.dropout = copy.deepcopy(
            pretrained_fusion.dropout
        )

        self.classifier = copy.deepcopy(
            pretrained_fusion.classifier
        )


    def forward(
        self,
        batch,
        return_z=False
    ):

        # GNN is now part of forward pass
        g = self.gnn.encode(
            batch.x,
            batch.edge_index,
            batch.batch
        )


        # Keep BERT dropout stable while still
        # allowing gradients through unfrozen layer
        self.bert.eval()

        bert_output = self.bert(
            input_ids=
                batch.input_ids,

            attention_mask=
                batch.attention_mask
        )

        H = (
            bert_output
            .last_hidden_state
        )


        q = self.graph_projection(
            g
        ).unsqueeze(1)


        attended, _ = (
            self.cross_attention(
                query=q,
                key=H,
                value=H,
                key_padding_mask=(
                    batch.attention_mask
                    == 0
                ),
                need_weights=False
            )
        )


        fused = torch.cat(
            [
                q.squeeze(1),
                attended.squeeze(1)
            ],
            dim=1
        )


        fused = self.norm(
            fused
        )

        z = F.relu(
            self.fc(
                fused
            )
        )

        z = self.dropout(
            z
        )

        logits = self.classifier(
            z
        )


