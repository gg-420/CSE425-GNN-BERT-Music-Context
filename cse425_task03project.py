from sklearn.metrics import (
    f1_score,
    average_precision_score
)


@torch.no_grad()
def evaluate_bert(
    loader,
    threshold=0.5
):

    bert_model.eval()

    all_targets = []
    all_probs = []

    total_loss = 0.0
    total_examples = 0


    for (
        input_ids,
        attention_mask,
        targets
    ) in loader:

        input_ids = input_ids.to(device)

        attention_mask = (
            attention_mask.to(device)
        )

        targets = targets.to(device)


        logits = bert_model(
            input_ids,
            attention_mask
        )


        loss = bert_criterion(
            logits,
            targets
        )


        probs = torch.sigmoid(
            logits
        )


        bs = targets.shape[0]

        total_loss += (
            loss.item() * bs
        )

        total_examples += bs


        all_targets.append(
            targets.cpu().numpy()
        )

        all_probs.append(
            probs.cpu().numpy()
        )


    y_true = np.concatenate(
        all_targets,
        axis=0
    )

    y_prob = np.concatenate(
        all_probs,
        axis=0
    )


    y_pred = (
        y_prob >= threshold
    ).astype(int)


    macro_f1 = f1_score(
        y_true,
        y_pred,
        average="macro",
        zero_division=0
    )

    micro_f1 = f1_score(
        y_true,
        y_pred,
        average="micro",
        zero_division=0
    )


    per_tag_ap = []

    for i in range(
        y_true.shape[1]
    ):

        per_tag_ap.append(
            average_precision_score(
                y_true[:, i],
                y_prob[:, i]
            )
        )


    return {

        "loss":
            total_loss
            / total_examples,

        "macro_f1":
            float(macro_f1),

        "micro_f1":
            float(micro_f1),

        "mean_auc_pr":
            float(
                np.mean(
                    per_tag_ap
                )
            ),

        "y_true":
            y_true,

        "y_prob":
            y_prob,

        "per_tag_ap":
            per_tag_ap
    }

